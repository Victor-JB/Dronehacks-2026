"""Assemble the standalone ROS 2 package `dh_nav_policy` from this branch's sources.

Same shape as the package that flew on 2026-11-07 (backup/testFiles: `test_files`): its own ament_python
package next to `dronehacks` in ~/team_ws/src, its own launch file starting flight_interface
(auto_offboard_on_arm + anchor_setpoints) and one command node, selected with COMPETITOR_PKG /
COMPETITOR_LAUNCH. It changes nothing in main; at run time it imports main's `refnav.depth` and
`dronehacks_nav.mapping` (exec_depend dronehacks_nav).

  python tools/integration/build_nav_policy_pkg.py integration/dh_nav_policy

The output is GENERATED: edit the sources (ros2_ws/src/dh_core, refnav/safety_filter.py,
ros2_ws/src/dh_autonomy) and re-run; test_integration_pkg.py fails if the copy is stale.
"""
import ast
import os
import shutil
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CORE = os.path.join(ROOT, "ros2_ws", "src", "dh_core", "dh_core")
AUTO = os.path.join(ROOT, "ros2_ws", "src", "dh_autonomy")
PKG = "dh_nav_policy"
CORE_MODULES = ["health.py", "planner_astar.py", "course.py", "mesh.py", "timing.py", "tracker.py",
                "stage5_interfaces.py"]
HEADER = "# GENERATED by tools/integration/build_nav_policy_pkg.py from {src} -- do not edit here.\n"

PACKAGE_XML = """<?xml version="1.0"?>
<package format="3">
  <name>dh_nav_policy</name>
  <version>0.1.0</version>
  <description>
    CAD-free exploration policy (nav_policy) for the skybeta drone. Same interface as the flown
    test_files package: /skybeta/setpoint/pose and /skybeta/setpoint/twist out, /skybeta/state and
    /visual_slam/tracking/odometry in; flight_interface owns /fmu/in/*. Also reads OAK depth + TF.
  </description>
  <maintainer email="sakethdesu@tamu.edu">DroneHacks team</maintainer>
  <license>Apache-2.0</license>

  <exec_depend>rclpy</exec_depend>
  <exec_depend>geometry_msgs</exec_depend>
  <exec_depend>nav_msgs</exec_depend>
  <exec_depend>sensor_msgs</exec_depend>
  <exec_depend>std_msgs</exec_depend>
  <exec_depend>std_srvs</exec_depend>
  <exec_depend>tf2_ros</exec_depend>
  <exec_depend>isaac_ros_visual_slam_interfaces</exec_depend>
  <exec_depend>skybeta_flight_interface</exec_depend>
  <exec_depend>dronehacks_nav</exec_depend>
  <exec_depend>launch</exec_depend>
  <exec_depend>launch_ros</exec_depend>
  <exec_depend>python3-numpy</exec_depend>
  <exec_depend>python3-scipy</exec_depend>

  <test_depend>python3-pytest</test_depend>

  <export>
    <build_type>ament_python</build_type>
  </export>
</package>
"""

SETUP_PY = """from glob import glob
from setuptools import setup

package_name = 'dh_nav_policy'

setup(
    name=package_name,
    version='0.1.0',
    packages=[package_name, package_name + '.navstack', package_name + '.navstack.nav',
              package_name + '.navstack.shadow'],
    data_files=[
        ('share/ament_index/resource_index/packages', ['resource/' + package_name]),
        ('share/' + package_name, ['package.xml']),
        ('share/' + package_name + '/launch', glob('launch/*.py')),
        ('share/' + package_name + '/config', glob('config/*.yaml')),
    ],
    install_requires=['setuptools'],
    tests_require=['pytest'],
    zip_safe=True,
    maintainer='DroneHacks team',
    maintainer_email='sakethdesu@tamu.edu',
    description='CAD-free exploration policy on the skybeta interface.',
    license='Apache-2.0',
    entry_points={
        'console_scripts': [
            'nav_policy = dh_nav_policy.node:main',
        ],
    },
)
"""

SETUP_CFG = "[develop]\nscript_dir=$base/lib/dh_nav_policy\n[install]\ninstall_scripts=$base/lib/dh_nav_policy\n"


def _w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write(text)


def _copy_py(src, dst, rel):
    with open(src, encoding="utf-8") as f:
        text = f.read()
    _w(dst, HEADER.format(src=rel) + text)


def _strip_px4_backend(src):
    """backends.py without Px4Backend (the only class that publishes /fmu/in/*)."""
    with open(src, encoding="utf-8") as f:
        text = f.read()
    tree = ast.parse(text)
    lines = text.splitlines(keepends=True)
    drop = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "Px4Backend":
            drop.append((node.lineno - 1 - len(node.decorator_list), node.end_lineno))
    for a, b in sorted(drop, reverse=True):
        del lines[a:b]
    out = "".join(lines)
    out = out.replace("Px4Backend  -", "(Px4Backend removed in this package) -")
    return out


def build(out):
    if os.path.isdir(out):
        shutil.rmtree(out)
    pkg = os.path.join(out, PKG)
    nav = os.path.join(pkg, "navstack")
    _w(os.path.join(nav, "__init__.py"), HEADER.format(src="(package marker)") +
       '"""Pure navigation stack (numpy only). Imports main\'s refnav.depth and dronehacks_nav.mapping."""\n')
    _copy_py(os.path.join(ROOT, "refnav", "safety_filter.py"), os.path.join(nav, "safety_filter.py"),
             "refnav/safety_filter.py")
    for m in CORE_MODULES:
        _copy_py(os.path.join(CORE, m), os.path.join(nav, m), "ros2_ws/src/dh_core/dh_core/" + m)
    for sub in ("nav", "shadow"):
        for f in sorted(os.listdir(os.path.join(CORE, sub))):
            if f.endswith(".py"):
                _copy_py(os.path.join(CORE, sub, f), os.path.join(nav, sub, f), "ros2_ws/src/dh_core/dh_core/%s/%s" % (sub, f))
    _w(os.path.join(pkg, "__init__.py"), HEADER.format(src="(package marker)"))
    _w(os.path.join(pkg, "backends.py"), HEADER.format(src="ros2_ws/src/dh_autonomy/dh_autonomy/backends.py (Px4Backend removed)")
       + _strip_px4_backend(os.path.join(AUTO, "dh_autonomy", "backends.py")))
    with open(os.path.join(AUTO, "dh_autonomy", "nav_policy_node.py"), encoding="utf-8") as f:
        node = f.read()
    node = node.replace("from dh_core.", "from dh_nav_policy.navstack.")
    _w(os.path.join(pkg, "node.py"), HEADER.format(src="ros2_ws/src/dh_autonomy/dh_autonomy/nav_policy_node.py") + node)
    with open(os.path.join(AUTO, "launch", "nav_policy.launch.py"), encoding="utf-8") as f:
        launch = f.read()
    launch = launch.replace('"dh_autonomy"', '"dh_nav_policy"').replace("ros2 launch dh_autonomy", "ros2 launch dh_nav_policy")
    _w(os.path.join(out, "launch", "nav_policy.launch.py"), HEADER.format(src="ros2_ws/src/dh_autonomy/launch/nav_policy.launch.py") + launch)
    shutil.copyfile(os.path.join(AUTO, "config", "nav_policy.yaml"), os.path.join(_mk(out, "config"), "nav_policy.yaml"))
    _w(os.path.join(out, "package.xml"), PACKAGE_XML)
    _w(os.path.join(out, "setup.py"), SETUP_PY)
    _w(os.path.join(out, "setup.cfg"), SETUP_CFG)
    _w(os.path.join(out, "resource", PKG), "")
    # focused pure tests, re-pointed at the package
    with open(os.path.join(ROOT, "ros2_ws", "src", "dh_core", "test", "test_nav.py"), encoding="utf-8") as f:
        t = f.read()
    t = t.replace("from dh_core.", "from dh_nav_policy.navstack.")
    t = t.replace('ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))',
                  'ROOT = os.environ.get("DRONEHACKS_MAIN", os.path.abspath(os.path.join(HERE, "..", "..", "dronehacks")))')
    t = t.replace('glob.glob(os.path.join(HERE, "..", "dh_core", "nav", "*.py"))',
                  'glob.glob(os.path.join(HERE, "..", "dh_nav_policy", "navstack", "nav", "*.py"))')
    _w(os.path.join(out, "test", "test_navstack.py"), HEADER.format(src="ros2_ws/src/dh_core/test/test_nav.py") + t)


def _mk(*parts):
    p = os.path.join(*parts)
    os.makedirs(p, exist_ok=True)
    return p


if __name__ == "__main__":
    build(os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "integration", PKG)))
    print("built", sys.argv[1] if len(sys.argv) > 1 else "integration/" + PKG)
